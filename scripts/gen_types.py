"""Generate TypeScript types for the case board from the Pydantic contracts.

    uv run python scripts/gen_types.py

Writes web/src/generated/contracts.ts. Do not edit that file by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from alibi import contracts as C

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "src" / "generated" / "contracts.ts"

MODELS = [C.Event, C.SourceInfo, C.EvidenceManifest, C.Finding, C.AttributionAssessment, C.Usage, C.ReviewEvent,
          C.InvestigationReport, C.Ratio, C.MatchRecord, C.FindingOutcome, C.EffectOutcome, C.Score,
          C.QuestionAnswer]


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    t = schema.get("type")
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    if t == "object":
        ap = schema.get("additionalProperties")
        return f"Record<string, {ts_type(ap) if isinstance(ap, dict) and ap else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def main() -> None:
    schema = TypeAdapter(tuple[tuple(MODELS)]).json_schema()  # type: ignore[valid-type]
    defs = schema.get("$defs", {})
    lines = ["// GENERATED by scripts/gen_types.py from src/alibi/contracts.py. Do not edit by hand.",
             "// Datetimes are ISO 8601 strings in UTC.", ""]
    for name in sorted(defs):
        d = defs[name]
        if d.get("type") != "object":
            lines.append(f"export type {name} = {ts_type(d)};\n")
            continue
        if d.get("description"):
            lines.append("/** " + " ".join(d["description"].split()) + " */")
        lines.append(f"export interface {name} {{")
        required = set(d.get("required", []))
        for prop, ps in d.get("properties", {}).items():
            opt = "" if prop in required else "?"
            lines.append(f"  {prop}{opt}: {ts_type(ps)};")
        lines.append("}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(defs)} types)")


if __name__ == "__main__":
    main()
