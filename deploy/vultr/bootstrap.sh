#!/usr/bin/env bash
# ALIBI on a Vultr Ubuntu 24.04 server: the offline recorded demo behind Caddy (automatic HTTPS).
# Idempotent; rerun it to update to the latest commit of ALIBI_REF. Run as root:
#
#   ALIBI_DOMAIN=whats-the-alibi.us bash bootstrap.sh
#
# Optional:  ALIBI_REF=<branch|tag|commit> (default codex/alibi-build)
#            ALIBI_REPO=<git url>          (default https://github.com/owly1/HackPrinceton.git; a private repo
#                                           needs a read-only deploy key or token configured for git by you)
#            ALIBI_BASIC_AUTH_USER / ALIBI_BASIC_AUTH_HASH  (hash from `caddy hash-password`) to put a login in front
# Without ALIBI_DOMAIN it serves plain HTTP on port 80 of the server's IP.
#
# The server runs with RUNTIME_MODE=offline and LLM_MAX_USD=0: no model calls, no API key, no spend.
set -euo pipefail

ALIBI_REPO="${ALIBI_REPO:-https://github.com/owly1/HackPrinceton.git}"
ALIBI_REF="${ALIBI_REF:-codex/alibi-build}"
ALIBI_DOMAIN="${ALIBI_DOMAIN:-}"
APP_DIR=/opt/alibi
HERE="$(cd "$(dirname "$0")" && pwd)"

[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
export DEBIAN_FRONTEND=noninteractive

echo "== packages"
apt-get update -y
apt-get install -y --no-install-recommends git curl ca-certificates gnupg debian-keyring debian-archive-keyring apt-transport-https ufw
if ! command -v node >/dev/null || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi
if ! command -v caddy >/dev/null; then
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
  apt-get update -y && apt-get install -y caddy
fi

echo "== service user and uv"
id alibi >/dev/null 2>&1 || useradd --system --create-home --home-dir /home/alibi --shell /usr/sbin/nologin alibi
if [ ! -x /home/alibi/.local/bin/uv ]; then
  sudo -u alibi -H bash -c 'curl -LsSf https://astral.sh/uv/install.sh | sh'
fi
UV=/home/alibi/.local/bin/uv

echo "== code at $ALIBI_REF"
if [ ! -d "$APP_DIR/.git" ]; then
  install -d -o alibi -g alibi "$APP_DIR"
  sudo -u alibi -H git clone "$ALIBI_REPO" "$APP_DIR"
fi
sudo -u alibi -H git -C "$APP_DIR" fetch --depth=50 origin "$ALIBI_REF"
sudo -u alibi -H git -C "$APP_DIR" checkout -B deploy FETCH_HEAD

echo "== build (Python deps from the lockfile, then the case board)"
sudo -u alibi -H bash -c "cd $APP_DIR && $UV sync --frozen --no-dev"
sudo -u alibi -H bash -c "cd $APP_DIR && npm --prefix web ci --no-audit --no-fund && npm --prefix web run build"

echo "== services"
install -m 644 "$HERE/alibi.service" /etc/systemd/system/alibi.service
systemctl daemon-reload
systemctl enable alibi
systemctl restart alibi

SITE="${ALIBI_DOMAIN:-:80}"
{
  echo "# generated by deploy/vultr/bootstrap.sh"
  echo "$SITE {"
  echo "	encode gzip"
  if [ -n "${ALIBI_BASIC_AUTH_USER:-}" ] && [ -n "${ALIBI_BASIC_AUTH_HASH:-}" ]; then
    echo "	basic_auth {"
    echo "		$ALIBI_BASIC_AUTH_USER $ALIBI_BASIC_AUTH_HASH"
    echo "	}"
  fi
  echo "	reverse_proxy 127.0.0.1:8000"
  echo "}"
  [ -n "$ALIBI_DOMAIN" ] && printf 'www.%s {\n\tredir https://%s{uri} permanent\n}\n' "$ALIBI_DOMAIN" "$ALIBI_DOMAIN"
} > /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile
systemctl enable caddy
systemctl reload caddy || systemctl restart caddy

echo "== firewall: ssh, http, https only"
ufw allow OpenSSH >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
ufw --force enable >/dev/null

echo "== health"
for _ in $(seq 1 30); do
  curl -fsS http://127.0.0.1:8000/api/runtime >/dev/null 2>&1 && break
  sleep 1
done
curl -fsS http://127.0.0.1:8000/api/runtime | head -c 300; echo
echo "done: ${ALIBI_DOMAIN:+https://$ALIBI_DOMAIN}${ALIBI_DOMAIN:-http://<server-ip>}  (commit $(git -C "$APP_DIR" rev-parse --short HEAD))"
